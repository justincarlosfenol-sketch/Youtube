"""Breakeven production CLI.

  python -m breakeven setup                         download open TTS model (Kokoro-82M, Apache-2.0)
  python -m breakeven brand                         render logo/banner/avatar/watermark
  python -m breakeven calendar --start 2026-12-01   rank ideas + write 90-day calendar
  python -m breakeven ideas discover                YouTube outlier research (YOUTUBE_API_KEY)
  python -m breakeven data refresh                  pull FRED series (FRED_API_KEY)
  python -m breakeven script <slug>                 readable script with timestamps + sources
  python -m breakeven teleprompter <slug>           numbered script for recording human narration
  python -m breakeven produce <slug>                model -> narration -> render -> thumbnails -> metadata -> shorts -> QA
  python -m breakeven still <slug> <shot> <t>       render one frame for review
  python -m breakeven qa <slug>
  python -m breakeven approve <slug> --thumbnail A-number [--title 0] [--allow-unverified]
  python -m breakeven upload <slug> [--publish-at 2026-12-01T15:00:00Z] [--dry-run]
  python -m breakeven analytics pull|demo|import-costs FILE|import-revenue FILE
  python -m breakeven dashboard [--demo]
"""
from __future__ import annotations

import argparse
import datetime as dt
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def vdir(slug: str) -> Path:
    p = ROOT / "videos" / slug
    if not p.exists():
        matches = list((ROOT / "videos").glob(f"{slug}*"))
        if len(matches) == 1:
            return matches[0]
        raise SystemExit(f"no video folder for '{slug}'")
    return p


def cmd_setup(_):
    from .tts import MODELS
    MODELS.mkdir(parents=True, exist_ok=True)
    base = "https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/"
    for f in ("kokoro-v1.0.onnx", "voices-v1.0.bin"):
        dst = MODELS / f
        if dst.exists():
            print("have", dst); continue
        print("downloading", f, "->", dst)
        subprocess.run(["curl", "-fL", "-o", str(dst), base + f], check=True)


def cmd_produce(a):
    from . import metadata, production, qa, shorts, thumbnails
    v = vdir(a.slug)
    production.render(v, workers=a.workers)
    thumbnails.render_all(v)
    metadata.build(v)
    shorts.make_shorts(v)
    rep = qa.run(v)
    qa.write(rep, v / "output" / "qa-report.md")
    print(f"QA: {len(rep.errors)} errors -> {v/'output'/'qa-report.md'}")


def cmd_teleprompter(a):
    import json
    from . import production
    v = vdir(a.slug)
    script = production.load(v)
    lines = ["# Teleprompter — " + script.get("working_title", a.slug), "",
             "Record each line as its own WAV file in `voice/` named exactly as the ID (e.g. `voice/s01_l00.wav`).",
             "Any line without a recording falls back to the draft TTS voice. Tips: dynamic USB mic, 15–20 cm from mouth,",
             "a closet or a room with soft furnishings, 1 s of silence before and after each take, re-record freely.",
             "Then run `python -m breakeven produce " + a.slug + "`; timing, captions and animation cues re-sync automatically.", ""]
    for si, sh in enumerate(script["shots"]):
        sid = sh.get("id", f"s{si:02d}")
        for li, ln in enumerate(sh.get("lines", [])):
            lid = ln.get("id", f"{sid}_l{li:02d}")
            have = "✅" if (v / "voice" / f"{lid}.wav").exists() else "⬜"
            lines.append(f"{have} **{lid}**  {ln['text'].replace('*', '')}\n")
    (v / "voice").mkdir(exist_ok=True)
    out = v / "voice" / "TELEPROMPTER.md"
    out.write_text("\n".join(lines))
    print(out)


def cmd_script(a):
    """Readable script (from the rendered timeline) with timestamps and sources."""
    import json
    import yaml
    v = vdir(a.slug)
    tl = json.loads((v / "output" / "timeline.json").read_text())
    src = yaml.safe_load((v / "sources.yaml").read_text())
    shots = {s["id"]: s for s in tl["shots"]}
    md = [f"# Script — {tl['slug']}", "", f"Runtime {int(tl['duration']//60)}:{int(tl['duration']%60):02d}. Narration numbers are bound to "
          "`data.json` (generated by `model.py`). Bracketed IDs cite `sources.yaml`.", ""]
    cur = None
    for sh in tl["shots"]:
        if sh["scene"] == "chapter":
            md += [f"## {sh['params'].get('number', '')} · {sh['params'].get('title', '')}", ""]
            continue
        if cur is None:
            md += ["## Cold open", ""]; cur = 1
        md.append(f"*[{sh['id']} · {sh['scene']}]*  ")
        for ln in [l for l in tl["lines"] if l["shot"] == sh["id"]]:
            t = ln["start"]; refs = " ".join(f"[{x}]" for x in ln.get("sources", []))
            md.append(f"`{int(t//60)}:{int(t%60):02d}` {ln['text'].replace('*', '')} {refs}  ")
        md.append("")
    md += ["## Sources", ""] + [f"- **{k}** — {x['claim']}. {x['source']}. {x.get('url', '')}" for k, x in src.items()]
    out = v / "SCRIPT.md"; out.write_text("\n".join(md) + "\n"); print(out)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="breakeven", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("setup"); sp.add_parser("brand")
    c = sp.add_parser("calendar"); c.add_argument("--start", default=str(dt.date.today()))
    i = sp.add_parser("ideas"); i.add_argument("action", choices=["discover"])
    d = sp.add_parser("data"); d.add_argument("action", choices=["refresh"])
    t = sp.add_parser("teleprompter"); t.add_argument("slug")
    sc = sp.add_parser("script"); sc.add_argument("slug")
    p = sp.add_parser("produce"); p.add_argument("slug"); p.add_argument("--workers", type=int, default=None)
    s = sp.add_parser("still"); s.add_argument("slug"); s.add_argument("shot"); s.add_argument("t", type=float)
    q = sp.add_parser("qa"); q.add_argument("slug")
    ap_ = sp.add_parser("approve"); ap_.add_argument("slug"); ap_.add_argument("--thumbnail", required=True)
    ap_.add_argument("--title", type=int, default=0); ap_.add_argument("--reviewer"); ap_.add_argument("--allow-unverified", action="store_true")
    u = sp.add_parser("upload"); u.add_argument("slug"); u.add_argument("--publish-at"); u.add_argument("--dry-run", action="store_true")
    an = sp.add_parser("analytics"); an.add_argument("action", choices=["pull", "demo", "import-costs", "import-revenue"]); an.add_argument("file", nargs="?")
    db = sp.add_parser("dashboard"); db.add_argument("--demo", action="store_true")
    a = ap.parse_args(argv)

    if a.cmd == "setup":
        cmd_setup(a)
    elif a.cmd == "brand":
        from .brand_assets import build_all
        for x in build_all():
            print(x)
    elif a.cmd == "calendar":
        from .planning import write_outputs
        print(write_outputs(dt.date.fromisoformat(a.start)))
    elif a.cmd == "ideas":
        from .research import discover
        print(discover())
    elif a.cmd == "data":
        from .research import refresh_fred
        refresh_fred()
    elif a.cmd == "script":
        cmd_script(a)
    elif a.cmd == "teleprompter":
        cmd_teleprompter(a)
    elif a.cmd == "produce":
        cmd_produce(a)
    elif a.cmd == "still":
        from .production import render_still
        v = vdir(a.slug); out = v / "output" / f"still_{a.shot}_{a.t:.1f}.png"
        print(render_still(v, a.shot, a.t, out))
    elif a.cmd == "qa":
        from . import metadata, qa
        v = vdir(a.slug); metadata.build(v); rep = qa.run(v); print(qa.write(rep, v / "output" / "qa-report.md"))
        for it in rep.items:
            print(f"{it['level']:5s} {it['check']}: {it['msg']}")
        sys.exit(1 if rep.errors else 0)
    elif a.cmd == "approve":
        from .upload import approve
        print(approve(vdir(a.slug), a.thumbnail, a.title, a.reviewer, a.allow_unverified))
    elif a.cmd == "upload":
        from .upload import upload
        upload(vdir(a.slug), a.publish_at, a.dry_run)
    elif a.cmd == "analytics":
        from . import analytics
        if a.action == "pull":
            analytics.pull()
        elif a.action == "demo":
            print(analytics.seed_demo())
        elif a.action == "import-costs":
            print(analytics.import_costs(Path(a.file)), "rows")
        else:
            print(analytics.import_revenue(Path(a.file)), "rows")
    elif a.cmd == "dashboard":
        from .dashboard import build
        print(build(demo=a.demo))


if __name__ == "__main__":
    main()
