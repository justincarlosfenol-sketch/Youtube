"""Idea prioritization and 90-day calendar generation.

Priority score (0-100): weighted sum of 1-5 ratings in content/ideas.csv
  search demand 25% | browse/curiosity appeal 20% | monetization value 20%
  evergreen 15%     | data availability 10%      | production ease 10%
Pinned ideas (pin_week) are scheduled first; the rest fill by score, with a
series-diversity rule (no series 3 weeks in a row) and seasonal preferences.
"""
from __future__ import annotations

import csv
import datetime as dt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDEAS = ROOT / "content" / "ideas.csv"

WEIGHTS = {"search": .25, "browse": .20, "value": .20, "evergreen": .15, "data": .10, "ease": .10}
SEASON_MONTHS = {"newyear": {12, 1}, "tax": {1, 2, 3, 4}, "holiday": {11, 12}, "rates": set(range(1, 13))}

# Publishing rhythm: flagship long-form Tuesday 10:00 ET; Shorts Mon/Wed/Fri
# (cut from the previous flagship). Community post Thursday.
FLAGSHIP_WEEKDAY = 1  # Tuesday
SHORT_OFFSETS = (1, 3, 6)  # days after the flagship: Wed, Fri, Mon


def load_ideas(path: Path = IDEAS) -> list[dict]:
    rows = list(csv.DictReader(open(path, newline="")))
    for r in rows:
        for k in ("search", "browse", "value", "evergreen", "data", "effort"):
            r[k] = int(r[k])
        r["ease"] = 6 - r["effort"]
        r["score"] = round(sum(r[k] * w for k, w in WEIGHTS.items()) / 5 * 100, 1)
        r["pin_week"] = int(r["pin_week"]) if r.get("pin_week") else None
    return rows


def ranked(rows: list[dict]) -> list[dict]:
    return sorted(rows, key=lambda r: (-r["score"], int(r["id"])))


def _next_weekday(d: dt.date, weekday: int) -> dt.date:
    return d + dt.timedelta(days=(weekday - d.weekday()) % 7)


def build_calendar(start: dt.date, days: int = 90, rows: list[dict] | None = None) -> list[dict]:
    rows = rows or load_ideas()
    first = _next_weekday(start, FLAGSHIP_WEEKDAY)
    weeks = []
    d = first
    while d < start + dt.timedelta(days=days):
        weeks.append(d)
        d += dt.timedelta(days=7)

    slots: dict[int, dict] = {}
    for r in rows:
        if r["pin_week"] and r["pin_week"] <= len(weeks):
            slots[r["pin_week"]] = r
    pool = [r for r in ranked(rows) if r not in slots.values()]
    for w in range(1, len(weeks) + 1):
        if w in slots:
            continue
        month = weeks[w - 1].month
        recent = [slots[k]["series"] for k in (w - 1, w - 2) if k in slots]
        def ok(r):
            if len(recent) == 2 and recent[0] == recent[1] == r["series"]:
                return False
            return not r["season"] or month in SEASON_MONTHS.get(r["season"], set())
        pick = next((r for r in pool if ok(r)), pool[0])
        slots[w] = pick
        pool.remove(pick)

    cal = []
    for w, date in enumerate(weeks, 1):
        r = slots[w]
        cal.append({"date": date.isoformat(), "type": "LONG-FORM", "week": w, "idea_id": r["id"],
                    "title": r["working_title"], "series": r["series"], "score": r["score"]})
        # 3 Shorts cut from this flagship (Wed, Fri, next Mon), each linking to it
        for n, offset in enumerate(SHORT_OFFSETS, 1):
            sd = date + dt.timedelta(days=offset)
            if sd < start + dt.timedelta(days=days):
                cal.append({"date": sd.isoformat(), "type": "SHORT", "week": w, "idea_id": r["id"],
                            "title": f"Short {n}/3 cut from: {r['working_title']}", "series": r["series"], "score": ""})
        thu = date + dt.timedelta(days=2)
        cal.append({"date": thu.isoformat(), "type": "COMMUNITY", "week": w, "idea_id": r["id"],
                    "title": "Poll/teaser: audience inputs for next model + link to free calculator",
                    "series": "", "score": ""})
    return sorted(cal, key=lambda x: (x["date"], x["type"]))


def write_outputs(start: dt.date) -> tuple[Path, Path]:
    rows = load_ideas()
    cal = build_calendar(start, rows=rows)
    out_csv = ROOT / "content" / "calendar-90d.csv"
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(cal[0].keys()))
        w.writeheader(); w.writerows(cal)
    md = ["# 90-Day Publishing Calendar", "",
          f"Generated by `python -m breakeven calendar --start {start}`. Long-form every Tuesday 10:00 ET; "
          "3 Shorts cut from each flagship (Wed, Fri, following Mon), each linking to it; Thursday community post.", "",
          "| Date | Type | Content | Series | Score |", "|---|---|---|---|---:|"]
    for c in cal:
        md.append(f"| {c['date']} | {c['type']} | {c['title']} | {c['series']} | {c['score']} |")
    md += ["", "# Idea backlog, ranked", "", "| Rank | ID | Working title | Series | Score |", "|---:|---:|---|---|---:|"]
    for i, r in enumerate(ranked(rows), 1):
        md.append(f"| {i} | {r['id']} | {r['working_title']} | {r['series']} | {r['score']} |")
    out_md = ROOT / "content" / "calendar-90d.md"
    out_md.write_text("\n".join(md) + "\n")
    return out_csv, out_md
